/* Helper to get total lessons count across all subjects */
export function getAllCurriculumLessons() {
  const all = [];
  SUBJECTS.forEach(sub => {
    sub.topics.forEach(top => {
      top.lessons.forEach(les => {
        all.push({
          ...les,
          subjectId: sub.id,
          subjectTitle: sub.title,
          subjectTitleBm: sub.title_bm,
          subjectEmoji: sub.emoji,
          subjectColor: sub.color,
          skillKey: sub.skillKey,
        });
      });
    });
  });
  return all;
}

export default SUBJECTS;
